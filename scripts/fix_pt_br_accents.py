def extract_string_span(line: str) -> tuple[int, int] | None:
    if "=>" not in line:
        return None
    arrow = line.index("=>")
    rest = line[arrow + 2 :]
    m = re.match(r"\s*(['\"])", rest)
    if not m:
        return None
    q = m.group(1)
    i = m.end()
    escaped = False
    while i < len(rest):
        c = rest[i]
        if escaped:
            escaped = False
            i += 1
            continue
        if c == "\\":
            escaped = True
            i += 1
            continue
        if c == q:
            inner_start = arrow + 2 + m.end()
            inner_end = arrow + 2 + i
            return (inner_start, inner_end)
        i += 1
    return None


