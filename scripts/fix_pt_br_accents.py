def process_file(path: Path, locale: str = "pt_BR") -> bool:
    text = path.read_text(encoding="utf-8")
    lines = text.splitlines(keepends=True)
    changed = False
    out: list[str] = []
    for line in lines:
        stripped = line.lstrip()
        if stripped.startswith("//") or stripped.startswith("*") or stripped.startswith("/*"):
            out.append(line)
            continue
        span = extract_string_span(line)
        if span is None:
            out.append(line)
            continue
        a, b = span
        inner = line[a:b]
        new_inner = transform_value(inner, locale=locale)
        if new_inner != inner:
            changed = True
            line = line[:a] + new_inner + line[b:]
        out.append(line)
    if changed:
        path.write_text("".join(out), encoding="utf-8")
    return changed


def main() -> int:
    lang = sys.argv[1] if len(sys.argv) > 1 else _DEFAULT_LANG
    if lang not in ("pt_BR", "pt_PT"):
        print("Uso: fix_pt_br_accents.py [pt_BR|pt_PT]", file=sys.stderr)
        return 2
    lang_path = lang_dir_for(lang)
    if not lang_path.is_dir():
        print(f"Diretório não encontrado: {lang_path}", file=sys.stderr)
        return 1
    n = 0
    for f in sorted(lang_path.rglob("*.php")):
        if process_file(f, locale=lang):
            print(f"Atualizado: {f.relative_to(ROOT)}")
            n += 1
    print(f"Total de arquivos modificados: {n}")
    return 0


